export const generateRecommendations = (areaScores) => {
  const areaRecommendations = [];
  const patterns = [];

  // Generar recomendaciones por área
  Object.entries(areaScores).forEach(([areaId, score]) => {
    let level;
    if (score <= 20) level = 'initial';
    else if (score <= 30) level = 'developing';
    else if (score <= 40) level = 'competent';
    else level = 'advanced';

    if (recommendations[areaId] && recommendations[areaId][level]) {
      areaRecommendations.push({
        area: areaId,
        score,
        level,
        ...recommendations[areaId][level]
      });
    }
  });

  // Detectar patrones cruzados
  crossPatterns.forEach(pattern => {
    if (pattern.condition(areaScores)) {
      patterns.push(pattern);
    }
  });

  // Ordenar recomendaciones por prioridad
  const priorityOrder = { 'CRÍTICA': 0, 'ALTA': 1, 'MEDIA': 2, 'BAJA': 3 };
  areaRecommendations.sort((a, b) => priorityOrder[a.priority] - priorityOrder[b.priority]);

  return {
    areaRecommendations,
    patterns,
    topPriorities: areaRecommendations.slice(0, 3)
  };
};

